const DICTS: Record<Locale, Dict> = { en, ja, ko, 'zh-Hans': zhHans, 'zh-Hant': zhHant };

// ---------------------------------------------------------------- store

const STORAGE_KEY = 'ashiato.locale';
let current: Locale = 'en';
const listeners = new Set<() => void>();

function emit() {
  listeners.forEach((l) => l());
}

function isLocale(v: any): v is Locale {
  return v === 'en' || v === 'ja' || v === 'ko' || v === 'zh-Hans' || v === 'zh-Hant';
}

/** ブラウザ／端末の言語から既定のロケールを決める。 */
function detectLocale(): Locale {
  try {
    const langs: string[] =
      typeof navigator !== 'undefined'
        ? ((navigator as any).languages?.length ? (navigator as any).languages : [navigator.language]).filter(Boolean)
        : [];
    for (const raw of langs) {
      const l = String(raw).toLowerCase();
      if (l.startsWith('ja')) return 'ja';
      if (l.startsWith('ko')) return 'ko';
      if (l.startsWith('zh')) {
        // 繁体字は zh-TW / zh-HK / zh-MO / zh-Hant
        return /hant|tw|hk|mo/.test(l) ? 'zh-Hant' : 'zh-Hans';
      }
      if (l.startsWith('en')) return 'en';
    }
  } catch {}
  return 'en';
}

/**
 * 起動時の復元。
 * 明示的に選ばれた設定（localStorage → DB）があればそれを、無ければブラウザの言語。
 */
async function restore() {
  // まずブラウザ言語を既定に
  current = detectLocale();
  emit();
  try {
    if (typeof window !== 'undefined') {
      const v = window.localStorage?.getItem(STORAGE_KEY);
      if (isLocale(v)) { current = v; emit(); }
    }
  } catch {}
  if (!isSupabaseConfigured) return;
  try {
    const { data } = await supabase.auth.getSession();
    const uid = data?.session?.user?.id;
    if (!uid) return;
    const { data: row } = await supabase.from('profiles').select('language').eq('id', uid).maybeSingle();
    if (row && isLocale(row.language)) { current = row.language; emit(); }
  } catch {}
}
let restored = false;

export async function setLocale(next: Locale) {
  current = next;
  emit();
  try {
    if (typeof window !== 'undefined') window.localStorage?.setItem(STORAGE_KEY, next);
  } catch {}
  if (!isSupabaseConfigured) return;
  try {
    const { data } = await supabase.auth.getSession();
    const uid = data?.session?.user?.id;
    if (uid) await supabase.from('profiles').update({ language: next }).eq('id', uid);
  } catch {}
}

export function getLocale(): Locale {
  return current;
}

/**
 * MATCHA のURLに使う言語セグメント。
 * DBには日本語版(/jp/)で入っているので、表示言語に合わせて差し替える。
 * 実際に叩いて該当ページが返ることを確認済み（en / ko / cn / tw）。
 */
const MATCHA_LANG: Record<Locale, string> = {
  en: 'en',
  ja: 'jp',
  ko: 'ko',
  'zh-Hans': 'cn',
  'zh-Hant': 'tw',
};

/** MATCHAのURLを現在の表示言語のものに置き換える。 */
export function localizeMatchaUrl(url: string | null | undefined): string | null {
  if (!url) return null;
  const seg = MATCHA_LANG[current] ?? 'en';
  return url.replace(/matcha-jp\.com\/[a-z]{2}\//i, `matcha-jp.com/${seg}/`);
}

/** 現在の言語での翻訳。辞書に無いキーは英語へフォールバック。 */
export function t(key: string, params?: Record<string, string | number>): string {
  let out = DICTS[current][key] ?? en[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => { out = out.replace(`{${k}}`, String(v)); });
  }
  return out;
}

export function useI18n() {
  const [, setTick] = useState(0);
  useEffect(() => {
    const l = () => setTick((n) => n + 1);
    listeners.add(l);
    if (!restored) { restored = true; restore(); }
    return () => { listeners.delete(l); };
  }, []);
  return { t, locale: current, setLocale };
}
